/**
 * The built-in starters (STU-1a). Boxes are in page pixels of the starter's format and stay inside its safe area
 * (decoration may bleed); every text box is generous for its sample copy and shrinks to fit longer copy. Hierarchy:
 * one display or heading line, supporting body, one call to action, the logo in a corner clear of everything else.
 */

