const logo = (corner: LogoSpec['corner'], width = 200): LogoSpec => ({ kind: 'logo', corner, width });

/** A pill button: a rounded rect and its label centred on it. */
const button = (
  x: number,
  y: number,
  width: number,
  height: number,
  label: string,
  fill: 'accent' | 'light',
  sizePx = 32,
): ElementSpec[] => [
  { kind: 'shape', name: 'Button', shape: 'rect', fill, box: [x, y, width, height], radius: height / 2 },
  {
    kind: 'text',
    name: 'Call to action',
    role: 'cta',
    text: label,
    typeRole: 'label',
    sizePx,
    align: 'center',
    box: [x, y + Math.round((height - sizePx * 1.2) / 2), width, Math.round(sizePx * 1.25)],
    on: fill,
    maxLength: 24,
  },
];

